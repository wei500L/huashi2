import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const PROJECT_ROOT = process.cwd();
const ENUMS_DIR = path.resolve(PROJECT_ROOT, 'shared-kernel/src/main/java/com/huashi/eftransfer/shared/enums');
const RESULT_CODE_FILE = path.resolve(PROJECT_ROOT, 'shared-kernel/src/main/java/com/huashi/eftransfer/shared/api/ResultCode.java');
const AI_PROTOCOLS_FILE = path.resolve(PROJECT_ROOT, 'shared-kernel/src/main/java/com/huashi/eftransfer/shared/ai/config/AiOpsProtocols.java');
const TARGET_FILE = path.resolve(PROJECT_ROOT, 'src/lib/contracts/generated/session-domain.ts');

function compareStrings(left, right) {
  return left.localeCompare(right, 'en');
}

function renderLiteralType(name, values) {
  return [
    `export const ${name}Values = ${JSON.stringify(values)} as const;`,
    `export type ${name} = typeof ${name}Values[number];`,
  ].join('\n');
}

function extractEnumName(source, filePath) {
  const match = source.match(/public enum\s+([A-Za-z0-9_]+)/);
  if (!match) {
    throw new Error(`Unable to locate enum name in ${filePath}`);
  }
  return match[1];
}

function extractEnumValues(source, filePath) {
  const enumHeaderMatch = source.match(/public enum\s+[A-Za-z0-9_]+\s*\{/);
  if (!enumHeaderMatch) {
    throw new Error(`Unable to locate enum body in ${filePath}`);
  }

  const body = source.slice(enumHeaderMatch.index + enumHeaderMatch[0].length);
  const terminatorIndex = body.indexOf(';');
  const constantsBlock = terminatorIndex >= 0 ? body.slice(0, terminatorIndex) : body;
  const matches = [...constantsBlock.matchAll(/^\s*([A-Z][A-Z0-9_]*)\s*(?:\(|,|$)/gm)].map((match) => match[1]);

  if (matches.length === 0) {
    throw new Error(`Unable to extract enum values from ${filePath}`);
  }
  return matches;
}

function extractStringConstants(source, filePath) {
  const matches = [...source.matchAll(/public static final String\s+([A-Z][A-Z0-9_]*)\s*=\s*"([^"]+)";/g)];
  if (matches.length === 0) {
    throw new Error(`Unable to extract string constants from ${filePath}`);
  }
  return matches.map((match) => match[2]);
}

async function loadJavaEnumContracts() {
  const files = (await readdir(ENUMS_DIR))
    .filter((fileName) => fileName.endsWith('.java'))
    .sort(compareStrings);

  const contracts = [];
  for (const fileName of files) {
    const filePath = path.join(ENUMS_DIR, fileName);
    const source = await readFile(filePath, 'utf8');
    contracts.push({
      name: extractEnumName(source, filePath),
      values: extractEnumValues(source, filePath),
    });
  }

  const resultCodeSource = await readFile(RESULT_CODE_FILE, 'utf8');
  contracts.push({
    name: 'ResultCode',
    values: extractEnumValues(resultCodeSource, RESULT_CODE_FILE),
  });

  const aiProtocolsSource = await readFile(AI_PROTOCOLS_FILE, 'utf8');
  contracts.push({
    name: 'AiOpsProtocol',
    values: extractStringConstants(aiProtocolsSource, AI_PROTOCOLS_FILE),
  });

  return contracts.sort((left, right) => compareStrings(left.name, right.name));
}

async function main() {
  const contracts = await loadJavaEnumContracts();
  const lines = [
    '// Generated by `npm run gen:contracts`. Do not edit by hand.',
    '',
  ];

  contracts.forEach((contract, index) => {
    if (index > 0) {
      lines.push('');
    }
    lines.push(renderLiteralType(contract.name, contract.values));
  });

  await mkdir(path.dirname(TARGET_FILE), { recursive: true });
  await writeFile(TARGET_FILE, `${lines.join('\n')}\n`, 'utf8');
  process.stdout.write(`Wrote ${TARGET_FILE}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});

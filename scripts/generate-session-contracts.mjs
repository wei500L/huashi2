import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const OPENAPI_URL = process.env.OPENAPI_URL || 'http://localhost:8080/v3/api-docs';
const AUTH_HEADER = process.env.OPENAPI_AUTH_HEADER;
const TARGET_FILE = path.resolve(process.cwd(), 'src/lib/contracts/generated/session-domain.ts');
const ENUM_SCHEMAS = [
  'AssessmentAttemptStatus',
  'ContextSupportLevel',
  'DiagnosisSessionStatus',
  'DiagnosisTaskType',
  'LexicalPairType',
  'TrainingCognitiveTag',
  'TrainingItemType',
  'TrainingMode',
  'TrainingSessionStatus',
];

function renderEnumType(schemaName, enumValues) {
  const renderedValues = enumValues.map((value) => `'${value}'`).join(' | ');
  return `export type ${schemaName} = ${renderedValues};`;
}

async function main() {
  const headers = AUTH_HEADER ? { Authorization: AUTH_HEADER } : undefined;
  const response = await fetch(OPENAPI_URL, { headers });
  if (!response.ok) {
    throw new Error(`Failed to fetch OpenAPI document from ${OPENAPI_URL}: ${response.status} ${response.statusText}`);
  }
  const document = await response.json();
  const schemas = document.components?.schemas;
  if (!schemas) {
    throw new Error('OpenAPI document does not contain components.schemas');
  }

  const lines = [
    '/* eslint-disable */',
    '// Generated by `npm run gen:contracts`. Do not edit by hand.',
    '',
  ];

  for (const schemaName of ENUM_SCHEMAS) {
    const schema = schemas[schemaName];
    if (!schema?.enum?.length) {
      throw new Error(`Schema ${schemaName} is missing or does not expose enum values`);
    }
    lines.push(renderEnumType(schemaName, schema.enum));
  }

  await mkdir(path.dirname(TARGET_FILE), { recursive: true });
  await writeFile(TARGET_FILE, `${lines.join('\n')}\n`, 'utf8');
  process.stdout.write(`Wrote ${TARGET_FILE}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
